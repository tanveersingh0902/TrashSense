def is_clearly_unrelated_image(label, confidence):
    """Return whether a strong ImageNet label names a known non-waste subject."""
    if confidence < MIN_UNRELATED_IMAGE_CONFIDENCE:
        return False

    normalized_label = label.casefold().replace(" ", "_")
    label_words = set(normalized_label.split("_"))
    return normalized_label in _NON_WASTE_LABEL_MARKERS or bool(
        label_words.intersection(_NON_WASTE_LABEL_MARKERS)
    )
